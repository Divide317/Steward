const cache = {};
export function icon(name, cls = '') {
  if (!cache[name]) {
    const rows = BITMAPS[name] || BITMAPS.crit;
    let rects = '';
    rows.forEach((row, y) => {
      for (let x = 0; x < 8;) {
        if (row[x] !== '#') { x++; continue; }
        let w = 1;
        while (row[x + w] === '#') w++;
        rects += `<rect x="${x}" y="${y}" width="${w}" height="1"/>`;
        x += w;
      }
    });
    cache[name] = rects;
  }
  return `<svg class="px ${cls}" viewBox="0 0 8 8" shape-rendering="crispEdges" aria-hidden="true" fill="currentColor">${cache[name]}</svg>`;
}

// Hydrate any <i data-icon="name"> placeholders already in the page.
export function hydrate(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) {
    if (!el.firstChild) el.innerHTML = icon(el.dataset.icon);
  }
}
